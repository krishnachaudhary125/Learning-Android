public class Datatype{
    public static void main(String[] args){
        int intNum = 1;
        float floatNum = 2.0f;
        double doubleNum = 3.0d;
        byte b = 0;
        short s = 100;
        char character = 'C';
        String greet = "Namaste";
        long longValue = 100000000;
        boolean result = true;

        System.out.println("Int = "+intNum+"\nFloat = "+floatNum+"\nDouble = "+doubleNum+"\nByte = "+b+"\nShort = "+s+"\nChar = "+character+"\nString = "+greet+"\nLong = "+longValue+"\nBoolean = "+result);
    }
}